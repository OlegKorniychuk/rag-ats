import { PRICING_CAVEAT } from '../parse-eval/cost.js';
import type { QuestionsMetrics } from './metrics.js';
import { BANDS } from './sample.js';

export interface QuestionsRunMeta {
  model: string;
  perBand: number;
  seed: number;
  /** Metered spend of the run (all calls, retries and failures included). */
  spentUsd: number;
  startedAt: string;
}

const pct = (share: number | null): string =>
  share === null ? 'n/a' : `${(100 * share).toFixed(1)} %`;

/** The metrics report (Markdown, formatted by the caller). */
export function renderQuestionsReport(
  label: string,
  metrics: QuestionsMetrics,
  meta: QuestionsRunMeta,
): string {
  const q = metrics.questionsPerApp;
  return [
    `# Interview questions eval: ${label}`,
    '',
    `Run ${meta.startedAt}, model \`${meta.model}\`, ${meta.perBand} scored application(s) per band (seed ${meta.seed}). Generated by \`npm run questions-eval\`; do not edit by hand.`,
    '',
    '## Generation',
    '',
    '| metric | value |',
    '| --- | --- |',
    `| applications | ${metrics.applications} |`,
    `| ok | ${metrics.ok} |`,
    `| ok after a retry | ${metrics.retried} |`,
    `| failed | ${metrics.failed} |`,
    `| questions per application (mean / min / max) | ${q.mean.toFixed(1)} / ${q.min} / ${q.max} |`,
    `| gap questions on a criterion scored below 50 | ${pct(metrics.gapOnLowCriterion)} |`,
    `| fact questions citing a unit the score cited | ${pct(metrics.factCitesScoreUnit)} |`,
    `| cost of ok calls (from tokens) | $${metrics.costUsd.toFixed(4)} |`,
    `| metered spend of the run | $${meta.spentUsd.toFixed(4)} |`,
    '',
    '## Fact / gap mix by band',
    '',
    '| band | fact | gap |',
    '| --- | --- | --- |',
    ...BANDS.map(
      (band) =>
        `| ${band} | ${metrics.basisByBand[band].fact} | ${metrics.basisByBand[band].gap} |`,
    ),
    '',
    PRICING_CAVEAT,
    '',
  ].join('\n');
}
